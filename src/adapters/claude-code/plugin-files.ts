import { join } from "node:path";
import { DATA_DIR_REL } from "../cli-path.js";

/**
 * The Claude Code plugin Parley installs, generated from constants (PLAN
 * section 6; loading mechanism confirmed in
 * .workbench/tasks/M4/plugin-loading.md and docs/harness-notes.md).
 *
 * A folder dropped into ~/.claude/plugins does NOT load. Claude Code loads a
 * plugin through a local directory *marketplace*: we write the plugin plus a
 * marketplace manifest under a stable path, then run `claude plugin install`.
 * Everything here is user-level and deterministic so install is idempotent and
 * uninstall can remove exactly these files.
 *
 * Every command these files run is the ABSOLUTE path to this install's launcher
 * (resolved at setup time, src/adapters/cli-path.ts) — never `npx`, which on a
 * registry name collision would download and run an unrelated package.
 */

/** The local marketplace root, relative to HOME: ~/.mcp-parley/claude-marketplace. */
export const MARKETPLACE_DIR_REL = join(DATA_DIR_REL, "claude-marketplace");

/** The marketplace name Claude Code registers it under. */
export const MARKETPLACE_NAME = "mcp-parley";

/** The plugin name inside the marketplace (install target is mcp-parley@mcp-parley). */
export const PLUGIN_NAME = "mcp-parley";

/** The plugin's location inside the marketplace (relative source path). */
export const PLUGIN_SUBDIR = join("plugins", "mcp-parley");

/** The user-level MCP config file Claude Code reads for user-scope servers. */
export const CLAUDE_JSON_REL = ".claude.json";

/**
 * The key Parley manages inside ~/.claude.json's mcpServers object. Not "parley":
 * that name is used by other tools (the Parley research platform registers its
 * own `parley` server), and the live test showed setup overwriting it.
 */
export const MCP_SERVER_KEY = "mcp-parley";

/**
 * The MCP server entry. `command` is the absolute launcher path (never `npx`).
 * `env` is the fix for the identity split: without it the per-session MCP
 * server resolves `mcp@<folder>` (PARLEY_HARNESS defaults to `mcp`) while the
 * hooks and monitor act as `claude@<folder>`. Setting PARLEY_HARNESS=claude
 * makes the MCP tools resolve to the SAME agent id as the hooks, so
 * `talk`/`inbox`/`agree` and the hooks share one inbox.
 */
export function mcpServerEntry(launcherPath: string): {
  command: string;
  args: string[];
  env: { PARLEY_HARNESS: string };
} {
  return {
    command: launcherPath,
    args: ["serve"],
    env: { PARLEY_HARNESS: "claude" },
  };
}

/**
 * One file install writes: a path relative to the marketplace root and its
 * exact contents. Install writes each; uninstall removes exactly these, then
 * prunes empty dirs.
 */
export interface PluginFile {
  rel: string;
  contents: string;
}

const PLUGIN_ROOT = "${CLAUDE_PLUGIN_ROOT}";

function script(body: string): string {
  return `#!/usr/bin/env sh\n# Generated by mcp-parley setup. Do not edit.\n${body}\n`;
}

/**
 * A hook script pipes its stdin JSON payload into the matching CLI command,
 * invoked by the absolute launcher path (never `npx`). The CLI sends its own
 * diagnostics to stderr, so a hook's stdout stays empty — a Claude Code hook's
 * stdout becomes model context, and only genuine deliveries (which the monitor
 * handles) belong there.
 */
function hookScript(launcherPath: string, event: string): string {
  return script(`exec "${launcherPath}" hook ${event}`);
}

const MARKETPLACE_MANIFEST = {
  name: MARKETPLACE_NAME,
  owner: { name: "mcp-parley" },
  description: "Local marketplace written by mcp-parley setup for the mcp-parley plugin.",
  plugins: [
    {
      name: PLUGIN_NAME,
      source: `./${PLUGIN_SUBDIR.split(/[/\\]/).join("/")}`,
      description: "Parley: let your coding agents message each other and settle agreements.",
    },
  ],
} as const;

const PLUGIN_MANIFEST = {
  name: PLUGIN_NAME,
  version: "0.1.0",
  author: { name: "mcp-parley" },
  description: "Parley: let your coding agents message each other and settle agreements.",
  experimental: {
    monitors: "./monitors/monitors.json",
  },
} as const;

const HOOKS_JSON = {
  hooks: {
    SessionStart: [
      {
        hooks: [{ type: "command", command: `"${PLUGIN_ROOT}/scripts/session-start.sh"` }],
      },
    ],
    UserPromptSubmit: [
      {
        hooks: [{ type: "command", command: `"${PLUGIN_ROOT}/scripts/user-prompt.sh"` }],
      },
    ],
    Stop: [
      {
        hooks: [{ type: "command", command: `"${PLUGIN_ROOT}/scripts/stop.sh"` }],
      },
    ],
    // A single PostToolUse entry: the handler itself decides whether the tool
    // was an edit (records the edit). It does NOT drain — see hook-events.ts:
    // delivery mid-turn is left to the monitor so no message is swallowed.
    // Registering it twice (matched + unmatched) processed every edit twice.
    PostToolUse: [
      {
        hooks: [{ type: "command", command: `"${PLUGIN_ROOT}/scripts/post-tool.sh"` }],
      },
    ],
    SessionEnd: [
      {
        hooks: [{ type: "command", command: `"${PLUGIN_ROOT}/scripts/session-end.sh"` }],
      },
    ],
  },
} as const;

/**
 * The monitor polls the inbox every 2 s and prints one line per message; what
 * it prints reaches Claude as a notification, waking an idle session (PLAN
 * section 6). It derives its agent id from the session cwd (it gets no
 * session_id). It must NOT give up if SessionStart hasn't registered the agent
 * yet (a start-of-session race): it registers the agent itself and keeps
 * polling for the life of the session.
 *
 * It passes a stable per-process session id (`monitor-<pid>`) to `inbox drain`
 * via --session, so monitor deliveries record a `delivered_session` and the
 * session-scoped requeue (SessionEnd / fresh-session) can act on them (review
 * finding: without --session delivered_session was NULL and requeue never ran).
 */
function monitorScript(launcherPath: string): string {
  return script(
    [
      'AGENT="claude@$(basename "$PWD")"',
      'SESSION="monitor-$$"',
      "# Make sure this folder's agent exists even if the monitor wins the race",
      "# with the SessionStart hook; `register` is idempotent.",
      `"${launcherPath}" inbox register --agent "$AGENT" >/dev/null 2>&1 || true`,
      "while :; do",
      `  "${launcherPath}" inbox drain --agent "$AGENT" --session "$SESSION" --format monitor`,
      "  # Exit when the parent harness process is gone.",
      '  if [ -n "$PPID" ] && ! kill -0 "$PPID" 2>/dev/null; then exit 0; fi',
      "  sleep 2",
      "done",
    ].join("\n"),
  );
}

const MONITORS_JSON = [
  {
    name: "mcp-parley-inbox",
    command: `"${PLUGIN_ROOT}/scripts/monitor.sh"`,
    description: "Parley messages from other agents",
  },
] as const;

function pretty(value: unknown): string {
  return `${JSON.stringify(value, null, 2)}\n`;
}

/**
 * Every file install writes, relative to the marketplace root
 * (~/.mcp-parley/claude-marketplace). The marketplace manifest sits at the root
 * under .claude-plugin/; the plugin itself lives under plugins/parley/. Every
 * script invokes the absolute launcher path (never `npx`).
 */
export function pluginFiles(launcherPath: string): PluginFile[] {
  const p = (rel: string): string => join(PLUGIN_SUBDIR, rel);
  return [
    {
      rel: join(".claude-plugin", "marketplace.json"),
      contents: pretty(MARKETPLACE_MANIFEST),
    },
    { rel: p(join(".claude-plugin", "plugin.json")), contents: pretty(PLUGIN_MANIFEST) },
    { rel: p(join("hooks", "hooks.json")), contents: pretty(HOOKS_JSON) },
    { rel: p(join("monitors", "monitors.json")), contents: pretty(MONITORS_JSON) },
    {
      rel: p(join("scripts", "session-start.sh")),
      contents: hookScript(launcherPath, "session-start"),
    },
    { rel: p(join("scripts", "user-prompt.sh")), contents: hookScript(launcherPath, "user-prompt") },
    { rel: p(join("scripts", "stop.sh")), contents: hookScript(launcherPath, "stop") },
    { rel: p(join("scripts", "post-tool.sh")), contents: hookScript(launcherPath, "post-tool") },
    { rel: p(join("scripts", "session-end.sh")), contents: hookScript(launcherPath, "session-end") },
    { rel: p(join("scripts", "monitor.sh")), contents: monitorScript(launcherPath) },
  ];
}

/** The path, relative to the marketplace root, where the monitor script lives. */
export const MONITOR_SCRIPT_REL = join(PLUGIN_SUBDIR, "scripts", "monitor.sh");
