import { join } from "node:path";

/**
 * The Claude Code plugin Parley installs, generated from constants (PLAN
 * section 6, formats verified in docs/harness-notes.md). Everything here is
 * user-level and deterministic so install is idempotent and uninstall can
 * remove exactly these files.
 */

/** Plugin root, relative to HOME: ~/.claude/plugins/parley. */
export const PLUGIN_DIR_REL = join(".claude", "plugins", "parley");

/** The user-level MCP config file Claude Code reads for user-scope servers. */
export const CLAUDE_JSON_REL = ".claude.json";

/** The key Parley manages inside ~/.claude.json's mcpServers object. */
export const MCP_SERVER_KEY = "parley";

export const MCP_SERVER_ENTRY = {
  command: "npx",
  args: ["parley-mcp", "serve"],
} as const;

/**
 * One plugin file: a path relative to the plugin root and its exact contents.
 * Install writes each; uninstall removes exactly these, then prunes empty dirs.
 */
export interface PluginFile {
  rel: string;
  contents: string;
}

const PLUGIN_ROOT = "${CLAUDE_PLUGIN_ROOT}";

function script(body: string): string {
  return `#!/usr/bin/env sh\n# Generated by parley-mcp setup. Do not edit.\n${body}\n`;
}

/** A hook script pipes its stdin JSON payload into the matching CLI command. */
function hookScript(event: string): string {
  return script(`exec npx parley-mcp hook ${event}`);
}

const PLUGIN_MANIFEST = {
  name: "parley",
  version: "0.1.0",
  description: "Parley: let your coding agents message each other and settle agreements.",
  experimental: {
    monitors: "./monitors/monitors.json",
  },
} as const;

const HOOKS_JSON = {
  hooks: {
    SessionStart: [
      {
        hooks: [{ type: "command", command: `"${PLUGIN_ROOT}/scripts/session-start.sh"` }],
      },
    ],
    UserPromptSubmit: [
      {
        hooks: [{ type: "command", command: `"${PLUGIN_ROOT}/scripts/user-prompt.sh"` }],
      },
    ],
    Stop: [
      {
        hooks: [{ type: "command", command: `"${PLUGIN_ROOT}/scripts/stop.sh"` }],
      },
    ],
    PostToolUse: [
      {
        matcher: "Edit|Write|MultiEdit",
        hooks: [{ type: "command", command: `"${PLUGIN_ROOT}/scripts/post-tool.sh"` }],
      },
      {
        hooks: [{ type: "command", command: `"${PLUGIN_ROOT}/scripts/post-tool.sh"` }],
      },
    ],
    SessionEnd: [
      {
        hooks: [{ type: "command", command: `"${PLUGIN_ROOT}/scripts/session-end.sh"` }],
      },
    ],
  },
} as const;

/**
 * The monitor polls the inbox every 2 s and prints one line per message; what
 * it prints reaches Claude as a notification, waking an idle session (PLAN
 * section 6). It derives its agent id from the session cwd (it gets no
 * session_id) and exits as soon as there are no Parley agents in the folder.
 */
const MONITORS_JSON = [
  {
    name: "parley-inbox",
    command: `"${PLUGIN_ROOT}/scripts/monitor.sh"`,
    description: "Parley messages from other agents",
  },
] as const;

const MONITOR_SCRIPT = script(
  [
    'AGENT="claude@$(basename "$PWD")"',
    "# Exit immediately when no Parley agent is registered for this folder.",
    'if ! npx parley-mcp who 2>/dev/null | grep -q "$AGENT"; then exit 0; fi',
    "while :; do",
    '  npx parley-mcp inbox drain --agent "$AGENT" --format monitor',
    "  # Exit when the parent harness process is gone.",
    '  if [ -n "$PPID" ] && ! kill -0 "$PPID" 2>/dev/null; then exit 0; fi',
    "  sleep 2",
    "done",
  ].join("\n"),
);

function pretty(value: unknown): string {
  return `${JSON.stringify(value, null, 2)}\n`;
}

/** Every file the plugin consists of, relative to the plugin root. */
export function pluginFiles(): PluginFile[] {
  return [
    { rel: join(".claude-plugin", "plugin.json"), contents: pretty(PLUGIN_MANIFEST) },
    { rel: join("hooks", "hooks.json"), contents: pretty(HOOKS_JSON) },
    { rel: join("monitors", "monitors.json"), contents: pretty(MONITORS_JSON) },
    { rel: join("scripts", "session-start.sh"), contents: hookScript("session-start") },
    { rel: join("scripts", "user-prompt.sh"), contents: hookScript("user-prompt") },
    { rel: join("scripts", "stop.sh"), contents: hookScript("stop") },
    { rel: join("scripts", "post-tool.sh"), contents: hookScript("post-tool") },
    { rel: join("scripts", "session-end.sh"), contents: hookScript("session-end") },
    { rel: join("scripts", "monitor.sh"), contents: MONITOR_SCRIPT },
  ];
}
