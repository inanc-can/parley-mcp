import { chmodSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Resolving the absolute command installed configs use to run THIS install's
 * CLI (the review's HIGH security finding: no installed MCP entry, hook or
 * monitor may ever run `npx`, which on a name collision would download and run
 * an unrelated third-party package).
 *
 * At setup time we write a tiny launcher into the user-level data dir
 * (~/.mcp-parley/bin/mcp-parley) that execs this repo's CLI, and we point every
 * generated config (MCP entry, hooks, monitor) at that launcher's ABSOLUTE
 * path. The launcher embeds the absolute path to this repo's CLI entry, so it
 * can never resolve to some other install or a package named on a registry.
 */

/** The data dir, relative to HOME (PLAN section 2: ~/.mcp-parley). */
export const DATA_DIR_REL = ".mcp-parley";

/** The launcher's path inside the data dir. */
export const LAUNCHER_REL = join(DATA_DIR_REL, "bin", "mcp-parley");

/** The CLI command name (PLAN: the published package/CLI is `mcp-parley`). */
export const CLI_NAME = "mcp-parley";

/**
 * The absolute path to this repo's CLI entry (src/cli/bin.ts). Derived from this
 * module's own location so it always points at the install that is running
 * setup, never at a registry package. There is no build pipeline yet (M12), so
 * the entry is the TypeScript source; the launcher runs it through the same
 * Node + loader this process is using (process.execPath + the resolved entry).
 */
export function cliEntryPath(): string {
  // This module compiles/runs from src/adapters/cli-path.(ts|js); the CLI entry
  // is ../cli/bin.(ts|js) relative to it. Resolve both candidates and prefer a
  // compiled .js when one exists (M12), else the .ts source (runnable via tsx).
  const here = dirname(fileURLToPath(import.meta.url));
  const jsEntry = resolve(here, "..", "cli", "bin.js");
  const tsEntry = resolve(here, "..", "cli", "bin.ts");
  return existsSync(jsEntry) ? jsEntry : tsEntry;
}

/**
 * The launcher script body. It execs this repo's CLI entry by absolute path,
 * never `npx`/`mcp-parley` off PATH. When the entry is TypeScript (no build
 * yet) it runs under `node --import tsx`; when a compiled .js exists it runs
 * under plain `node`. `process.execPath` pins the exact Node running setup.
 */
export function launcherScript(nodePath: string, entry: string): string {
  const isTs = entry.endsWith(".ts");
  const nodeInvocation = isTs
    ? `exec "${nodePath}" --import tsx ${quote(entry)} "$@"`
    : `exec "${nodePath}" ${quote(entry)} "$@"`;
  return [
    "#!/usr/bin/env sh",
    "# Generated by mcp-parley setup. Runs THIS install's CLI by absolute path.",
    "# Do not edit; re-run `mcp-parley setup` to regenerate.",
    nodeInvocation,
    "",
  ].join("\n");
}

function quote(path: string): string {
  return `"${path}"`;
}

/**
 * The absolute path of the launcher for a given HOME. This is the `command`
 * every generated config (MCP entry, hooks, monitor) uses.
 */
export function launcherPath(home: string): string {
  return join(home, LAUNCHER_REL);
}

/**
 * Write (idempotently) the launcher into ~/.mcp-parley/bin/mcp-parley and make
 * it executable. Returns its absolute path. Called once by setup before it
 * writes the per-harness configs so they can point at it. Writing into the data
 * dir is user-level, never a repo write.
 */
export function ensureLauncher(home: string, execPath: string = process.execPath): string {
  const path = launcherPath(home);
  const body = launcherScript(execPath, cliEntryPath());
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, body, "utf8");
  chmodSync(path, 0o755);
  return path;
}
